import { readdir, writeFile } from 'node:fs/promises';
import { extname, basename, resolve } from 'node:path';

const root = resolve(globalThis.process.cwd());
const galleryDirectory = resolve(root, 'public/images/gallery');
const outputFile = resolve(root, 'src/config/gallery-manifest.ts');
const supportedExtensions = new Set(['.webp', '.jpg', '.jpeg', '.png', '.avif']);

const files = (await readdir(galleryDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && supportedExtensions.has(extname(entry.name).toLowerCase()))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, undefined, { numeric: true, sensitivity: 'base' }));

const entries = files.map((file, index) => {
  const id = basename(file, extname(file)).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || `gallery-${index + 1}`;
  const src = `/images/gallery/${encodeURIComponent(file)}`;
  return `  { id: '${id}', src: '${src}', alt: 'Khoảnh khắc cưới ${index + 1}' },`;
});

const content = `// Generated by scripts/generate-gallery-manifest.mjs. Do not edit manually.\nexport const gallery = [\n${entries.join('\n')}\n] as const;\n`;
await writeFile(outputFile, content, 'utf8');
globalThis.console.log(`Generated gallery manifest with ${files.length} image${files.length === 1 ? '' : 's'}.`);
